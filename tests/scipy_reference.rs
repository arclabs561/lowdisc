#[test]
fn sobol_matches_scipy_in_all_eight_dimensions() {
    let mut generator = SobolGenerator::new(8);
    for (index, expected) in SCIPY_SOBOL_8D.iter().enumerate() {
        assert_eq!(
            generator.next(),
            expected,
            "Sobol point {index} differs from SciPy"
        );
    }
}

#[test]
fn halton_matches_scipy_in_all_eight_dimensions() {
    for (index, expected) in SCIPY_HALTON_8D.iter().enumerate() {
        let got = halton_point(index, 8);
        for (dim, (g, e)) in got.iter().zip(expected).enumerate() {
            assert!(
                (g - e).abs() < 1e-15,
                "Halton point {index} dim {dim}: {g} vs SciPy {e}"
            );
        }
    }
}
